#!/usr/bin/env bash
# Tests actions/new-deps/new_deps.py: in a temporary git repository, a base
# commit's Cargo.lock against a changed working-tree Cargo.lock, checking the
# annotations, the job summary, and that the exit status stays 0. Needs bash,
# git and python3 (3.11 or later).
set -uo pipefail

src_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
script="${src_root}/actions/new-deps/new_deps.py"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

# The test's own repository: no user or system git config.
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null
export GIT_AUTHOR_NAME=test GIT_AUTHOR_EMAIL=test@example.invalid
export GIT_COMMITTER_NAME=test GIT_COMMITTER_EMAIL=test@example.invalid

registry='registry+https://github.com/rust-lang/crates.io-index'

# lock <name> <version> <source>... prints a Cargo.lock holding those
# packages; a source of -- means none (a workspace member).
lock() {
  printf '# This file is automatically @generated by Cargo.\nversion = 4\n'
  while [[ $# -ge 3 ]]; do
    printf '\n[[package]]\nname = "%s"\nversion = "%s"\n' "$1" "$2"
    [[ $3 == -- ]] || printf 'source = "%s"\n' "$3"
    shift 3
  done
}

failures=0

# run_case <name> <base lock or "none"> <head lock or "none"> <want>... -- <unwanted>...
# Commits the base lock (no Cargo.lock for "none"), writes the head lock to the
# working tree, runs new_deps.py with the base commit, and checks that the
# output and summary hold every wanted string and none of the unwanted ones.
run_case() {
  local name="$1" base="$2" head="$3" out code repo="${work}/repo" summary="${work}/summary.md"
  shift 3
  rm -rf "${repo}" "${summary}" && mkdir -p "${repo}"
  git -C "${repo}" init --quiet
  git -C "${repo}" commit --quiet --allow-empty -m root
  if [[ ${base} != none ]]; then
    printf '%s\n' "${base}" >"${repo}/Cargo.lock"
    git -C "${repo}" add Cargo.lock
    git -C "${repo}" commit --quiet -m base
  fi
  local sha
  sha="$(git -C "${repo}" rev-parse HEAD)"
  if [[ ${head} == none ]]; then
    rm -f "${repo}/Cargo.lock"
  else
    printf '%s\n' "${head}" >"${repo}/Cargo.lock"
  fi
  out="$(cd "${repo}" && GITHUB_STEP_SUMMARY="${summary}" python3 -I "${script}" "${sha}" 2>&1)"
  code=$?
  [[ -f ${summary} ]] && out+=$'\n'"$(<"${summary}")"
  local bad="" unwanted=0 s
  for s in "$@"; do
    if [[ ${s} == -- ]]; then
      unwanted=1
    elif [[ ${unwanted} -eq 0 && ${out} != *"${s}"* ]]; then
      bad+=" missing [${s}]"
    elif [[ ${unwanted} -eq 1 && ${out} == *"${s}"* ]]; then
      bad+=" unwanted [${s}]"
    fi
  done
  if [[ ${code} -ne 0 ]]; then
    echo "FAIL ${name}: exit ${code}, want 0"
    printf '%s\n' "${out}" | sed 's/^/    /'
    failures=$((failures + 1))
  elif [[ -n ${bad} ]]; then
    echo "FAIL ${name}:${bad}; output:"
    printf '%s\n' "${out}" | sed 's/^/    /'
    failures=$((failures + 1))
  else
    echo "ok   ${name}"
  fi
}

base="$(lock app 0.1.0 -- serde 1.0.200 "${registry}" libc 0.2.150 "${registry}")"

run_case "unchanged lock adds nothing" "${base}" "${base}" \
  "Cargo.lock adds no crates." -- "::warning" "::notice"

run_case "new crate is a warning, in the summary" "${base}" \
  "$(lock app 0.1.0 -- serde 1.0.200 "${registry}" libc 0.2.150 "${registry}" itoa 1.0.11 "${registry}")" \
  "::warning title=New dependency::new crate: itoa 1.0.11 from https://github.com/rust-lang/crates.io-index" \
  "| \`itoa\` | 1.0.11 | https://github.com/rust-lang/crates.io-index | new crate |" \
  -- "serde" "libc" "::notice"

run_case "new version of a known crate is a notice" "${base}" \
  "$(lock app 0.1.0 -- serde 1.0.210 "${registry}" libc 0.2.150 "${registry}")" \
  "::notice title=New dependency::new version: serde 1.0.210" "new version |" \
  -- "::warning" "1.0.200"

run_case "second version beside the old one is a notice" "${base}" \
  "$(lock app 0.1.0 -- serde 1.0.200 "${registry}" libc 0.2.150 "${registry}" libc 0.1.12 "${registry}")" \
  "::notice title=New dependency::new version: libc 0.1.12" -- "::warning" "0.2.150"

run_case "known crate from a git source is a warning" "${base}" \
  "$(lock app 0.1.0 -- serde 1.0.200 "${registry}" libc 0.2.150 "${registry}" \
    serde 1.0.200 "git+https://github.com/serde-rs/serde?rev=abc#0123456789abcdef")" \
  "::warning title=New dependency::new crate: serde 1.0.200 from https://github.com/serde-rs/serde?rev=abc" \
  -- "0123456789abcdef"

run_case "removed crate is not reported" "${base}" \
  "$(lock app 0.1.0 -- serde 1.0.200 "${registry}")" \
  "Cargo.lock adds no crates." -- "libc" "::warning"

run_case "new workspace member is left out" "${base}" \
  "$(lock app 0.1.0 -- tool 0.1.0 -- serde 1.0.200 "${registry}" libc 0.2.150 "${registry}")" \
  "Cargo.lock adds no crates." -- "tool" "::warning"

run_case "no lock at the base: every crate is new" none "${base}" \
  "new crate: serde 1.0.200" "new crate: libc 0.2.150" -- "app" "::notice"

run_case "no lock in the working tree: nothing to compare" "${base}" none \
  "No Cargo.lock in the working tree" -- "::warning"

run_case "unparsable lock warns, doesn't fail" "${base}" "not = = toml" \
  "::warning title=New dependency::could not compare Cargo.lock"

# A base commit that isn't in the repository, as when the checkout is shallow.
rm -rf "${work}/repo" && mkdir -p "${work}/repo" && git -C "${work}/repo" init --quiet
lock serde 1.0.200 "${registry}" >"${work}/repo/Cargo.lock"
out="$(cd "${work}/repo" && python3 -I "${script}" 0000000000000000000000000000000000000001 2>&1)"
code=$?
if [[ ${code} -eq 0 && ${out} == *"::warning title=New dependency::could not compare"*"not in the checkout"* ]]; then
  echo "ok   missing base commit warns, doesn't fail"
else
  echo "FAIL missing base commit: exit ${code}, output:"
  printf '%s\n' "${out}" | sed 's/^/    /'
  failures=$((failures + 1))
fi

if [[ ${failures} -ne 0 ]]; then
  echo "${failures} case(s) failed"
  exit 1
fi
echo "all new-deps cases passed"
